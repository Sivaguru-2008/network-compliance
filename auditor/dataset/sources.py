def get_sources_for_vendor(vendor: str) -> List[VendorSource]:
    """Retrieve list of sources for a specific vendor or all vendors."""
    normalized = vendor.lower().strip()
    if normalized == "all":
        result = []
        for src_list in VENDOR_SOURCES.values():
            result.extend(src_list)
        return result
    return VENDOR_SOURCES.get(normalized, [])


def get_all_vendor_keys() -> List[str]:
    """Retrieve all supported vendor keys."""
    return list(VENDOR_SOURCES.keys())
