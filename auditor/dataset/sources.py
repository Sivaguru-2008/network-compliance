"""Authoritative vendor source catalog based on the Vendor CLI / Config Reference Index."""

from dataclasses import dataclass, field
from enum import Enum
from typing import Dict, List, Optional


class AccessType(str, Enum):
    OPEN = "open"  # Direct public PDF / HTML downloadable
    FREE_ACCOUNT = "free_acct"  # Viewable/downloadable with a free vendor account
    FRAGMENTED = "fragmented"  # Distributed per-product / fragmented across lines
    ACCESS_REQUIRES_ACCOUNT = "access_requires_account"


class DocumentFormat(str, Enum):
    PDF = "pdf"
    HTML = "html"
    MARKDOWN = "markdown"
    JSON = "json"


@dataclass
class VendorSource:
    vendor_key: str
    vendor_name: str
    os_name: str
    config_format: str
    doc_title: str
    url: str
    access_type: AccessType
    doc_format: DocumentFormat
    direct_download: bool
    version: str = "latest"
    description: str = ""
    target_filename: str = ""
    is_authoritative: bool = True
    backup_urls: List[str] = field(default_factory=list)


